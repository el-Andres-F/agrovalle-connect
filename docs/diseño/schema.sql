CREATE TABLE IF NOT EXISTS productores (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(255) NOT NULL,
    ubicacion VARCHAR(255) NOT NULL,
    cedula VARCHAR(255) NOT NULL,
    contacto VARCHAR(255)
);
CREATE TABLE IF NOT EXISTS compradores (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(255) NOT NULL,
    apellido VARCHAR(100),
    correo VARCHAR(255) NOT NULL,
    telefono VARCHAR(255) NOT NULL,
    contrasena_hash VARCHAR(255) NOT NULL
);
CREATE TABLE IF NOT EXISTS admin (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario VARCHAR(80) NOT NULL UNIQUE,
    contrasena_hash VARCHAR(100) NOT NULL,
    nombre VARCHAR(100),
    apellido VARCHAR(100),
    correo VARCHAR(160)
);
CREATE TABLE IF NOT EXISTS productos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(255), categoria VARCHAR(255), cantidad INTEGER,
    fecha_cosecha DATE, precio DOUBLE PRECISION, ubicacion VARCHAR(255),
    productor_id BIGINT REFERENCES productores(id)
);
CREATE TABLE IF NOT EXISTS pedidos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    referencia VARCHAR(80) NOT NULL UNIQUE,
    comprador_id BIGINT NOT NULL REFERENCES compradores(id),
    total NUMERIC(14,2) NOT NULL, estado VARCHAR(30) NOT NULL,
    fecha_creacion TIMESTAMP NOT NULL, direccion_entrega VARCHAR(200)
);
CREATE TABLE IF NOT EXISTS pedido_detalles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id BIGINT NOT NULL REFERENCES pedidos(id) ON DELETE CASCADE,
    producto_id BIGINT NOT NULL REFERENCES productos(id),
    cantidad INTEGER NOT NULL CHECK (cantidad > 0),
    precio_unitario NUMERIC(14,2) NOT NULL CHECK (precio_unitario >= 0)
);
CREATE INDEX IF NOT EXISTS idx_productos_productor_id ON productos(productor_id);
CREATE UNIQUE INDEX IF NOT EXISTS uq_productores_cedula ON productores(cedula);
CREATE UNIQUE INDEX IF NOT EXISTS uq_compradores_correo ON compradores(correo);
CREATE INDEX IF NOT EXISTS idx_pedidos_comprador_fecha ON pedidos(comprador_id, fecha_creacion DESC);
CREATE INDEX IF NOT EXISTS idx_detalles_producto_id ON pedido_detalles(producto_id);
